#!/usr/bin/env python3
"""Generate fmt/<TABLE>.xml and sql/40-load-vocab.sql from sql/10-cdm-tables.sql.

The format files exist for one reason: SQL Server on Linux has no BULK INSERT
CODEPAGE option, so without them the Athena CSVs (UTF-8) are read in a legacy
code page and every non-ASCII concept name is mangled. Declaring each varchar
field's COLLATION as UTF-8 makes BULK INSERT read the bytes as UTF-8.

    tools/make-vocab-load.py [path/to/athena/vocab]

With a vocabulary directory, each file's header is checked against the DDL's
column order, which the format files assume.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
UTF8 = 'Latin1_General_100_CI_AS_SC_UTF8'
TABLES = ['VOCABULARY', 'DOMAIN', 'CONCEPT_CLASS', 'RELATIONSHIP', 'CONCEPT',
          'CONCEPT_SYNONYM', 'CONCEPT_RELATIONSHIP', 'CONCEPT_ANCESTOR', 'DRUG_STRENGTH']

ddl = (ROOT / 'sql/10-cdm-tables.sql').read_text()
vocab = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else None

load = [
    '-- Load the Athena vocabulary CSVs (tab-separated, UTF-8, header row) with',
    '-- BULK INSERT. Generated by tools/make-vocab-load.py; do not edit by hand.',
    '-- sqlcmd variables: CDM_SCHEMA, VOCAB_DIR and FMT_DIR (paths in the container).',
    '',
]
for t in TABLES:
    m = re.search(r'CREATE TABLE \$\(CDM_SCHEMA\)\.%s \((.*?)\);' % t, ddl, re.S)
    cols = [line.strip().rstrip(',').split()[:2] for line in m.group(1).strip().splitlines() if line.strip()]
    names = [c[0].strip('"') for c in cols]
    if vocab:
        header = (vocab / f'{t}.csv').open(encoding='utf-8').readline().rstrip('\n').split('\t')
        if [h.lower() for h in header] != [n.lower() for n in names]:
            sys.exit(f'{t}: CSV header {header} does not match DDL {names}')

    fields, columns = [], []
    for i, (name, typ) in enumerate(cols, 1):
        term = '\\n' if i == len(cols) else '\\t'
        coll = f' COLLATION="{UTF8}"' if typ.lower().startswith('varchar') else ''
        fields.append(f'  <FIELD ID="{i}" xsi:type="CharTerm" TERMINATOR="{term}" MAX_LENGTH="4000"{coll}/>')
        columns.append(f'  <COLUMN SOURCE="{i}" NAME="{name.strip(chr(34))}"/>')
    (ROOT / f'fmt/{t}.xml').write_text(
        '<?xml version="1.0"?>\n'
        '<BCPFORMAT xmlns="http://schemas.microsoft.com/sqlserver/2004/bulkload/format" '
        'xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">\n <RECORD>\n'
        + '\n'.join(fields) + '\n </RECORD>\n <ROW>\n' + '\n'.join(columns)
        + '\n </ROW>\n</BCPFORMAT>\n')

    load += [
        f"PRINT CONCAT(CONVERT(varchar(19), SYSDATETIME(), 120), ' loading {t}');",
        f'TRUNCATE TABLE $(CDM_SCHEMA).{t};',
        f"BULK INSERT $(CDM_SCHEMA).{t} FROM '$(VOCAB_DIR)/{t}.csv'",
        f"  WITH (FORMATFILE = '$(FMT_DIR)/{t}.xml', FIRSTROW = 2, TABLOCK, BATCHSIZE = 500000, MAXERRORS = 0);",
        f"SELECT '{t}' AS loaded, COUNT_BIG(*) AS row_count FROM $(CDM_SCHEMA).{t};",
        'GO',
        '',
    ]
    print(f'{t}: {len(cols)} columns' + ('; header matches DDL' if vocab else ''))

(ROOT / 'sql/40-load-vocab.sql').write_text('\n'.join(load))
